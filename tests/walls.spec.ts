import { test, expect } from '@playwright/test'

test('wall presets have distinct default tags and independent editable footprints with shared history', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create layout' }).click()
  const board = page.getByRole('region', { name: 'Terrain board' })
  await expect(page.getByLabel('Scalable wall footprint preview')).toBeVisible()
  await page.getByLabel('Scalable wall footprint preview').dragTo(board, { targetPosition: { x: 180, y: 180 } })
  await expect(page.getByLabel('Terrain width')).toHaveValue('6')
  await expect(page.getByLabel('Terrain depth')).toHaveValue('1')
  await expect(page.getByRole('checkbox', { name: 'Climbable', exact: true })).toBeChecked()
  await expect(page.getByRole('checkbox', { checked: true })).toHaveCount(1)
  await expect(page.getByText('Blocks LOS: No')).toBeVisible()
  await page.getByLabel('Terrain width').fill('9')
  await page.getByLabel('Terrain depth').fill('2')
  await page.getByLabel('X position').fill('10')
  await page.getByLabel('Y position').fill('10')
  await page.getByLabel('Rotation (degrees)').fill('90')
  await page.getByLabel('Colour', { exact: true }).fill('#123456')
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  await page.getByRole('button', { name: 'Duplicate terrain' }).click()
  await page.getByLabel('Terrain depth').fill('3')
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByLabel('Terrain depth')).toHaveValue('2')
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(page.getByLabel('Terrain depth')).toHaveValue('3')
  await page.getByLabel('Tall wall footprint preview').dragTo(board, { targetPosition: { x: 360, y: 360 } })
  await expect(page.getByLabel('Terrain width')).toHaveValue('6')
  await expect(page.getByLabel('Terrain depth')).toHaveValue('1')
  await expect(page.getByRole('checkbox', { name: 'Impassable', exact: true })).toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Sight Blocking', exact: true })).toBeChecked()
  await expect(page.getByRole('checkbox', { checked: true })).toHaveCount(2)
  await expect(page.getByText('Blocks LOS: Yes')).toBeVisible()
  await expect(page.getByLabel('Terrain height')).toHaveCount(0)
  await page.getByLabel('Units').selectOption('cm')
  const library = page.getByRole('complementary', { name: 'Terrain library' })
  await expect(library.getByRole('button', { name: 'Scalable wall · 15.24 cm × 2.54 cm' })).toBeVisible()
  await expect(library.getByRole('button', { name: 'Tall wall · 15.24 cm × 2.54 cm' })).toBeVisible()
  await expect(page.getByLabel('Terrain width')).toHaveValue('15.24')
  await expect(page.getByLabel('Terrain depth')).toHaveValue('2.54')
  await page.getByLabel('Terrain depth').fill('5.08')
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  await page.getByLabel('Units').selectOption('in')
  await page.getByLabel('X position').fill('20')
  await page.getByLabel('Y position').fill('20')
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  const bounds = (await board.boundingBox())!
  const scale = bounds.width / 48
  await page.mouse.move(bounds.x + 23 * scale, bounds.y + 21 * scale)
  await page.mouse.down()
  await page.mouse.move(bounds.x + 25 * scale, bounds.y + 24 * scale, { steps: 10 })
  await page.mouse.up()
  await expect(page.getByLabel('X position')).toHaveValue('22')
  await expect(page.getByLabel('Y position')).toHaveValue('23')
  await page.getByRole('button', { name: 'Scalable wall 2', exact: true }).click()
  await page.getByRole('button', { name: 'Delete terrain' }).click()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByLabel('Terrain depth')).toHaveValue('3')
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(page.getByRole('heading', { name: '2 terrain pieces', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Scalable wall 1', exact: true }).click()
  await expect(page.getByLabel('Terrain width')).toHaveValue('9')
  await expect(page.getByLabel('Terrain depth')).toHaveValue('2')
  await expect(page.getByLabel('Rotation (degrees)')).toHaveValue('90')
  await expect(page.getByLabel('Colour', { exact: true })).toHaveValue('#123456')
  await page.getByRole('button', { name: 'Scalable wall 2', exact: true }).click()
  await expect(page.getByLabel('Terrain depth')).toHaveValue('3')
  await page.getByRole('button', { name: 'Tall wall 3', exact: true }).click()
  await expect(page.getByLabel('Terrain width')).toHaveValue('6')
  await expect(page.getByLabel('Terrain depth')).toHaveValue('2')
  await expect(page.getByLabel('X position')).toHaveValue('22')
  await expect(page.getByLabel('Y position')).toHaveValue('23')
})

test('walls reuse edited, renamed and deleted layout tags for existing and later placements', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create layout' }).click()
  const board = page.getByRole('region', { name: 'Terrain board' })
  const settings = page.getByRole('button', { name: 'Layout settings' })
  const dialog = page.getByRole('dialog', { name: 'Layout settings' })
  await page.getByLabel('Scalable wall footprint preview').dragTo(board, { targetPosition: { x: 180, y: 180 } })
  await page.getByLabel('Tall wall footprint preview').dragTo(board, { targetPosition: { x: 300, y: 300 } })
  await settings.click()
  await dialog.getByRole('checkbox', { name: 'Climbable Blocks LOS' }).check()
  await dialog.getByRole('checkbox', { name: 'Sight Blocking Blocks LOS' }).uncheck()
  await dialog.getByRole('textbox', { name: 'Tag name: Climbable', exact: true }).fill('Scaling')
  await dialog.getByRole('textbox', { name: 'Tag name: Sight Blocking', exact: true }).fill('Opaque')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Blocks LOS: No')).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Opaque', exact: true })).toBeChecked()
  await page.getByRole('button', { name: 'Scalable wall 1', exact: true }).click()
  await expect(page.getByText('Blocks LOS: Yes')).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Scaling', exact: true })).toBeChecked()
  await page.getByLabel('Scalable wall footprint preview').dragTo(board, { targetPosition: { x: 420, y: 420 } })
  await expect(page.getByText('Blocks LOS: Yes')).toBeVisible()
  await page.getByRole('checkbox', { name: 'Scaling', exact: true }).uncheck()
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  await expect(page.getByText('Blocks LOS: No')).toBeVisible()
  await page.getByRole('button', { name: 'Scalable wall 1', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Scaling', exact: true })).toBeChecked()
  await page.getByLabel('Tall wall footprint preview').dragTo(board, { targetPosition: { x: 480, y: 480 } })
  await expect(page.getByText('Blocks LOS: No')).toBeVisible()
  await settings.click()
  const pending = page.waitForEvent('dialog')
  const click = dialog.getByRole('listitem', { name: 'Opaque', exact: true }).getByRole('button', { name: 'Delete', exact: true }).click()
  const prompt = await pending
  expect(prompt.message()).toContain('2 placed pieces')
  await prompt.accept()
  await click
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Tall wall 2', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Opaque', exact: true })).toHaveCount(0)
  await expect(page.getByRole('checkbox', { name: 'Impassable', exact: true })).toBeChecked()
  await expect(page.getByText('Blocks LOS: No')).toBeVisible()
  await page.getByLabel('Tall wall footprint preview').dragTo(board, { targetPosition: { x: 540, y: 540 } })
  await expect(page.getByRole('checkbox', { checked: true })).toHaveCount(1)
  await expect(page.getByText('Blocks LOS: No')).toBeVisible()
  await page.getByRole('button', { name: 'Scalable wall 1', exact: true }).click()
  await expect(page.getByText('Blocks LOS: Yes')).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Scaling', exact: true })).toBeChecked()
  await page.getByRole('button', { name: 'Scalable wall 3', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Scaling', exact: true })).not.toBeChecked()
})

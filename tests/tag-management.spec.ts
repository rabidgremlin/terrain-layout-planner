import { test, expect } from '@playwright/test'

test('supplied tag rename preserves membership and reaches catalog choices, history, and reload', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create layout' }).click()
  const board = page.getByRole('region', { name: 'Terrain board' })
  const settings = page.getByRole('button', { name: 'Layout settings' })
  const dialog = page.getByRole('dialog', { name: 'Layout settings' })
  await page.getByLabel('Building footprint preview').dragTo(board, { targetPosition: { x: 180, y: 180 } })
  await settings.click()
  await dialog.getByRole('textbox', { name: 'Tag name: Sight Blocking', exact: true }).fill('  Opaque  ')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Opaque', exact: true })).toBeChecked()
  await expect(page.getByText('Blocks LOS: Yes')).toBeVisible()
  await expect(page.getByRole('complementary', { name: 'Terrain library' })).toContainText('Impassable · Opaque')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Sight Blocking', exact: true })).toBeChecked()
  await settings.click()
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Redo', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await page.getByLabel('Building footprint preview').dragTo(board, { targetPosition: { x: 360, y: 360 } })
  await expect(page.getByRole('checkbox', { name: 'Opaque', exact: true })).toBeChecked()
  await page.reload()
  await page.getByRole('button', { name: 'Building 1', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Opaque', exact: true })).toBeChecked()
  await expect(page.getByLabel('Terrain width')).toHaveValue('6')
  await settings.click()
  await expect(dialog.getByRole('listitem', { name: 'Opaque', exact: true })).toContainText('2 pieces')
})

test('deletions are confirmed and drafted, then restore definitions, memberships and catalog associations together', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create layout' }).click()
  const board = page.getByRole('region', { name: 'Terrain board' })
  const settings = page.getByRole('button', { name: 'Layout settings' })
  const dialog = page.getByRole('dialog', { name: 'Layout settings' })
  const row = (name: string) => dialog.getByRole('listitem', { name, exact: true })
  async function remove(name: string, count: number, accept = true) {
    await expect(row(name).getByRole('button', { name: 'Delete', exact: true })).toBeVisible()
    const promptPromise = page.waitForEvent('dialog')
    const click = row(name).getByRole('button', { name: 'Delete', exact: true }).click()
    const prompt = await promptPromise
    expect(prompt.message()).toContain(name)
    expect(prompt.message()).toContain(`${count} placed ${count === 1 ? 'piece' : 'pieces'}`)
    expect(prompt.message()).toContain('catalog associations')
    if (accept) await prompt.accept()
    else await prompt.dismiss()
    await click
  }
  await page.getByLabel('Building footprint preview').dragTo(board, { targetPosition: { x: 180, y: 180 } })
  await page.getByRole('checkbox', { name: 'Dense', exact: true }).check()
  await page.getByLabel('Terrain width').fill('9')
  await page.getByLabel('Terrain depth').fill('2')
  await page.getByLabel('X position').fill('10')
  await page.getByLabel('Y position').fill('12')
  await page.getByLabel('Rotation (degrees)').fill('30')
  await page.getByLabel('Colour', { exact: true }).fill('#123456')
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  await settings.click()
  await dialog.getByRole('textbox', { name: 'Tag name: Sight Blocking', exact: true }).fill('Opaque')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await settings.click()
  await remove('Opaque', 1, false)
  await expect(row('Opaque')).toBeVisible()
  await remove('Opaque', 1)
  await expect(row('Opaque')).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Opaque', exact: true })).toBeChecked()
  await settings.click()
  await remove('Opaque', 1)
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Blocks LOS: Yes')).toBeVisible()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await settings.click()
  await remove('Opaque', 1)
  await remove('Dense', 1)
  await remove('Dangerous', 0)
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Blocks LOS: No')).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Opaque', exact: true })).toHaveCount(0)
  await expect(page.getByRole('checkbox', { name: 'Impassable', exact: true })).toBeChecked()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Opaque', exact: true })).toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Dense', exact: true })).toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Dangerous', exact: true })).not.toBeChecked()
  await expect(page.getByRole('complementary', { name: 'Terrain library' })).toContainText('Impassable · Opaque')
  await settings.click()
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Redo', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Building 1', exact: true }).click()
  await expect(page.getByText('Blocks LOS: No')).toBeVisible()
  await expect(page.getByLabel('Terrain width')).toHaveValue('9')
  await expect(page.getByLabel('Terrain depth')).toHaveValue('2')
  await expect(page.getByLabel('X position')).toHaveValue('10')
  await expect(page.getByLabel('Y position')).toHaveValue('12')
  await expect(page.getByLabel('Rotation (degrees)')).toHaveValue('30')
  await expect(page.getByLabel('Colour', { exact: true })).toHaveValue('#123456')
  await page.getByLabel('Building footprint preview').dragTo(board, { targetPosition: { x: 360, y: 360 } })
  await expect(page.getByText('Blocks LOS: No')).toBeVisible()
  await expect(page.getByRole('checkbox', { checked: true })).toHaveCount(1)
  await expect(page.getByRole('checkbox', { name: 'Opaque', exact: true })).toHaveCount(0)
  await settings.click()
  await expect(row('Opaque')).toHaveCount(0)
  await expect(row('Dense')).toHaveCount(0)
  await expect(row('Dangerous')).toHaveCount(0)
})

test('custom renames validate the whole draft and retain edited flags and memberships through deletion history', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create layout' }).click()
  const settings = page.getByRole('button', { name: 'Layout settings' })
  const dialog = page.getByRole('dialog', { name: 'Layout settings' })
  const row = (name: string) => dialog.getByRole('listitem', { name, exact: true })
  await settings.click()
  for (const name of ['Magic mist', 'Unused']) {
    await dialog.getByLabel('New tag').fill(name)
    await dialog.getByRole('button', { name: 'Add tag' }).click()
  }
  await row('Magic mist').getByRole('checkbox').check()
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByLabel('Barricade footprint preview').dragTo(page.getByRole('region', { name: 'Terrain board' }), { targetPosition: { x: 180, y: 180 } })
  await page.getByRole('checkbox', { name: 'Magic mist', exact: true }).check()
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  await settings.click()
  await dialog.getByRole('textbox', { name: 'Tag name: Cover', exact: true }).fill('Shelter')
  await dialog.getByRole('textbox', { name: 'Tag name: Magic mist', exact: true }).fill('   ')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('name for every tag')
  await dialog.getByRole('textbox', { name: 'Tag name:', exact: true }).fill(' shelter ')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('unique')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Cover', exact: true })).toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Magic mist', exact: true })).toBeChecked()
  await settings.click()
  await dialog.getByRole('textbox', { name: 'Tag name: Magic mist', exact: true }).fill('  Ancient  ')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Ancient', exact: true })).toBeChecked()
  await expect(page.getByText('Blocks LOS: Yes')).toBeVisible()
  await settings.click()
  await expect(row('Ancient')).toContainText('1 piece')
  await expect(row('Ancient').getByRole('checkbox')).toBeChecked()
  for (const name of ['Ancient', 'Unused']) {
    const pending = page.waitForEvent('dialog')
    const click = row(name).getByRole('button', { name: 'Delete', exact: true }).click()
    const prompt = await pending
    expect(prompt.message()).toContain(name === 'Ancient' ? '1 placed piece' : '0 placed pieces')
    await prompt.accept()
    await click
  }
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Blocks LOS: No')).toBeVisible()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Ancient', exact: true })).toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Unused', exact: true })).not.toBeChecked()
  await expect(page.getByText('Blocks LOS: Yes')).toBeVisible()
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Barricade 1', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Ancient', exact: true })).toHaveCount(0)
  await expect(page.getByRole('checkbox', { name: 'Unused', exact: true })).toHaveCount(0)
  await expect(page.getByRole('checkbox', { name: 'Cover', exact: true })).toBeChecked()
})

test('recreating a deleted supplied name does not restore catalog associations or change fresh defaults', async ({ page, browser }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create layout' }).click()
  await page.getByRole('button', { name: 'Layout settings' }).click()
  const dialog = page.getByRole('dialog', { name: 'Layout settings' })
  const pending = page.waitForEvent('dialog')
  const click = dialog.getByRole('listitem', { name: 'Sight Blocking', exact: true }).getByRole('button', { name: 'Delete', exact: true }).click()
  await (await pending).accept()
  await click
  await dialog.getByLabel('New tag').fill('Sight Blocking')
  await dialog.getByRole('button', { name: 'Add tag' }).click()
  await dialog.getByRole('listitem', { name: 'Sight Blocking', exact: true }).getByRole('checkbox').check()
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await page.reload()
  await page.getByLabel('Building footprint preview').dragTo(page.getByRole('region', { name: 'Terrain board' }), { targetPosition: { x: 180, y: 180 } })
  await expect(page.getByRole('checkbox', { name: 'Sight Blocking', exact: true })).not.toBeChecked()
  await expect(page.getByText('Blocks LOS: No')).toBeVisible()
  const fresh = await browser.newPage()
  try {
    await fresh.goto(page.url())
    await fresh.getByRole('button', { name: 'Create layout' }).click()
    await fresh.getByLabel('Building footprint preview').dragTo(fresh.getByRole('region', { name: 'Terrain board' }), { targetPosition: { x: 180, y: 180 } })
    await expect(fresh.getByRole('checkbox', { name: 'Sight Blocking', exact: true })).toBeChecked()
    await expect(fresh.getByText('Blocks LOS: Yes')).toBeVisible()
  } finally { await fresh.close() }
})

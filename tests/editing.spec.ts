import { test, expect } from '@playwright/test'

test('exact terrain geometry survives unit changes and reload', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create layout' }).click()
  await page.locator('.preview').dragTo(page.getByRole('region', { name: 'Terrain board' }), { targetPosition: { x: 180, y: 180 } })
  await page.getByLabel('Terrain width').fill('8.5')
  await page.getByLabel('Terrain height').fill('3.25')
  await page.getByLabel('X position').fill('10.125')
  await page.getByLabel('Y position').fill('12.5')
  await page.getByLabel('Rotation (degrees)').fill('90')
  await page.getByRole('button', { name: 'Apply geometry' }).click()
  await page.getByLabel('Units').selectOption('cm')
  await expect(page.getByLabel('Terrain width')).toHaveValue('21.59')
  await expect(page.getByLabel('Terrain height')).toHaveValue('8.255')
  await expect(page.getByLabel('X position')).toHaveValue('25.7175')
  await expect(page.getByLabel('Y position')).toHaveValue('31.75')
  await expect(page.getByRole('heading', { name: 'Firefight · 121.92 cm × 121.92 cm' })).toBeVisible()
  await page.getByLabel('Terrain width').fill('25.4')
  await page.getByRole('button', { name: 'Apply geometry' }).click()
  await page.getByLabel('Units').selectOption('in')
  await expect(page.getByLabel('Terrain width')).toHaveValue('10')
  await page.reload()
  await page.getByRole('button', { name: 'Building 1', exact: true }).click()
  await expect(page.getByLabel('Terrain width')).toHaveValue('10')
  await expect(page.getByLabel('Terrain height')).toHaveValue('3.25')
  await expect(page.getByLabel('X position')).toHaveValue('10.125')
  await expect(page.getByLabel('Rotation (degrees)')).toHaveValue('90')
})

test('one history handles edits, independent duplication, removal, undo, redo, and branching', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create layout' }).click()
  const undo = page.getByRole('button', { name: 'Undo', exact: true })
  const redo = page.getByRole('button', { name: 'Redo', exact: true })
  await expect(undo).toBeDisabled()
  await page.locator('.preview').dragTo(page.getByRole('region', { name: 'Terrain board' }), { targetPosition: { x: 180, y: 180 } })
  await page.getByLabel('Terrain width').fill('9')
  await page.getByLabel('Rotation (degrees)').fill('45')
  await page.getByRole('button', { name: 'Apply geometry' }).click()
  await page.getByRole('button', { name: 'Duplicate terrain' }).click()
  await page.getByLabel('Terrain width').fill('12')
  await page.getByRole('button', { name: 'Apply geometry' }).click()
  await page.getByRole('button', { name: 'Building 1', exact: true }).click()
  await expect(page.getByLabel('Terrain width')).toHaveValue('9')
  await page.getByRole('button', { name: 'Building 2', exact: true }).click()
  await page.getByRole('button', { name: 'Remove terrain' }).click()
  await expect(page.getByText('1 terrain piece', { exact: true })).toBeVisible()
  await undo.click()
  await expect(page.getByLabel('Terrain width')).toHaveValue('12')
  await undo.click()
  await expect(page.getByLabel('Terrain width')).toHaveValue('9')
  await undo.click()
  await expect(page.getByText('1 terrain piece', { exact: true })).toBeVisible()
  await undo.click()
  await page.getByRole('button', { name: 'Building 1', exact: true }).click()
  await expect(page.getByLabel('Terrain width')).toHaveValue('6')
  await expect(page.getByLabel('Rotation (degrees)')).toHaveValue('0')
  await redo.click()
  await expect(page.getByLabel('Terrain width')).toHaveValue('9')
  await expect(page.getByLabel('Rotation (degrees)')).toHaveValue('45')
  await redo.click()
  await redo.click()
  await redo.click()
  await expect(page.getByText('1 terrain piece', { exact: true })).toBeVisible()
  await undo.click()
  await page.getByRole('button', { name: 'Building 2', exact: true }).click()
  await page.getByLabel('Terrain height').fill('5')
  await page.getByRole('button', { name: 'Apply geometry' }).click()
  await expect(redo).toBeDisabled()
  await page.reload()
  await page.getByRole('button', { name: 'Building 2', exact: true }).click()
  await expect(page.getByLabel('Terrain width')).toHaveValue('12')
  await expect(page.getByLabel('Terrain height')).toHaveValue('5')
})

test('snapping applies to drops and moves; disabled snapping preserves fractional positions', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create layout' }).click()
  await page.getByLabel('Snap to grid').check()
  await page.getByLabel('Grid spacing').fill('2')
  await page.getByLabel('Grid spacing').press('Tab')
  const board = page.getByRole('region', { name: 'Terrain board' })
  const bounds = (await board.boundingBox())!
  const scale = bounds.width / 48
  await page.locator('.preview').dragTo(board, { targetPosition: { x: 10.3 * scale, y: 10.3 * scale } })
  await expect(page.getByLabel('X position')).toHaveValue('8')
  await expect(page.getByLabel('Y position')).toHaveValue('8')
  await page.mouse.move(bounds.x + 9 * scale, bounds.y + 9 * scale)
  await page.mouse.down()
  await page.mouse.move(bounds.x + 12.3 * scale, bounds.y + 14.3 * scale, { steps: 10 })
  await page.mouse.up()
  await expect(page.getByLabel('X position')).toHaveValue('12')
  await expect(page.getByLabel('Y position')).toHaveValue('14')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByLabel('X position')).toHaveValue('8')
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(page.getByLabel('Y position')).toHaveValue('14')
  await page.getByLabel('Snap to grid').uncheck()
  await page.mouse.move(bounds.x + 13 * scale, bounds.y + 15 * scale)
  await page.mouse.down()
  await page.mouse.move(bounds.x + 14.4 * scale, bounds.y + 16.6 * scale, { steps: 10 })
  await page.mouse.up()
  await expect.poll(async () => Number(await page.getByLabel('X position').inputValue())).toBeCloseTo(13.4, 1)
  await expect.poll(async () => Number(await page.getByLabel('Y position').inputValue())).toBeCloseTo(15.6, 1)
  await page.reload()
  await page.getByRole('button', { name: 'Building 1', exact: true }).click()
  await expect.poll(async () => Number(await page.getByLabel('X position').inputValue())).toBeCloseTo(13.4, 1)
})

test('a visual quarter turn matches numeric geometry and can be undone', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create layout' }).click()
  const board = page.getByRole('region', { name: 'Terrain board' })
  await page.locator('.preview').dragTo(board, { targetPosition: { x: 225, y: 225 } })
  const bounds = (await board.boundingBox())!
  // Piece bounds: (180,195) to (270,255); rotation handle at (225,171).
  await page.mouse.move(bounds.x + 225, bounds.y + 171)
  await page.mouse.down()
  await page.mouse.move(bounds.x + 279, bounds.y + 225, { steps: 20 })
  await page.mouse.up()
  await expect.poll(async () => Number(await page.getByLabel('Rotation (degrees)').inputValue())).toBeCloseTo(90, 0)
  await expect(page.getByLabel('Terrain width')).toHaveValue('6')
  await expect(page.getByLabel('Terrain height')).toHaveValue('4')
  // Rotating about the centre moves the local top-left to (17,12).
  await expect.poll(async () => Number(await page.getByLabel('X position').inputValue())).toBeCloseTo(17, 1)
  await expect.poll(async () => Number(await page.getByLabel('Y position').inputValue())).toBeCloseTo(12, 1)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByLabel('Rotation (degrees)')).toHaveValue('0')
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Building 1', exact: true }).click()
  await expect.poll(async () => Number(await page.getByLabel('Rotation (degrees)').inputValue())).toBeCloseTo(90, 0)
})

test('centimetre board setup and numeric transforms match the rendered footprint', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Board size').selectOption('custom')
  await page.getByLabel('Units').selectOption('cm')
  await expect(page.getByLabel('Width (centimetres)')).toHaveValue('121.92')
  await page.getByLabel('Width (centimetres)').fill('91.44')
  await page.getByLabel('Height (centimetres)').fill('91.44')
  await page.getByRole('button', { name: 'Create layout' }).click()
  await page.getByLabel('Units').selectOption('in')
  await expect(page.getByRole('heading', { name: 'Firefight · 36″ × 36″' })).toBeVisible()
  const board = page.getByRole('region', { name: 'Terrain board' })
  await page.locator('.preview').dragTo(board, { targetPosition: { x: 180, y: 180 } })
  await page.getByLabel('Terrain width').fill('0')
  await page.getByRole('button', { name: 'Apply geometry' }).click()
  await expect(page.getByRole('alert')).toContainText('positive')
  await page.getByLabel('Terrain width').fill('8')
  await page.getByLabel('Terrain height').fill('2')
  await page.getByLabel('X position').fill('10')
  await page.getByLabel('Y position').fill('10')
  await page.getByLabel('Rotation (degrees)').fill('90')
  await page.getByRole('button', { name: 'Apply geometry' }).click()
  await page.reload()
  const bounds = (await board.boundingBox())!
  const scale = bounds.width / 36
  // The 8×2 rectangle at (10,10), rotated clockwise 90°, covers x=8..10,y=10..18.
  await page.mouse.click(bounds.x + 9 * scale, bounds.y + 17 * scale)
  await expect(page.getByLabel('Terrain width')).toHaveValue('8')
  await page.mouse.click(bounds.x + 14 * scale, bounds.y + 11 * scale)
  await expect(page.getByLabel('Selected terrain')).toHaveCount(0)
})

import { test, expect } from '@playwright/test'

const legacyLayout = {
  version: 1, game: 'custom', board: { width: 36, height: 24 },
  pieces: [{
    id: 'legacy-building', name: 'Building',
    footprint: { kind: 'rectangle', width: 6, height: 4 },
    x: 7.125, y: 8.25, rotation: 30, colour: '#a8b89c',
    tags: ['Impassable', 'Sight Blocking'], visibility: 'blocking',
  }],
}

test('existing saved layouts retain geometry, autosave undo, and reload without history or preferences', async ({ page }) => {
  await page.addInitScript(layout => {
    const key = 'terrain-planner.current-layout.v1'
    if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify(layout))
  }, legacyLayout)
  await page.goto('/')
  const undo = page.getByRole('button', { name: 'Undo', exact: true })
  const redo = page.getByRole('button', { name: 'Redo', exact: true })
  await expect(page.getByRole('heading', { name: 'Custom game · 36″ × 24″' })).toBeVisible()
  await expect(undo).toBeDisabled()
  await expect(redo).toBeDisabled()
  await expect(page.getByLabel('Selected terrain')).toHaveCount(0)
  await page.getByRole('button', { name: 'Building 1', exact: true }).click()
  await expect(page.getByLabel('X position')).toHaveValue('7.125')
  await expect(page.getByLabel('Y position')).toHaveValue('8.25')
  await expect(page.getByLabel('Rotation (degrees)')).toHaveValue('30')
  await page.getByLabel('Terrain width').fill('9')
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  await undo.click()
  await expect(page.getByLabel('Terrain width')).toHaveValue('6')
  await redo.click()
  await expect(page.getByLabel('Terrain width')).toHaveValue('9')
  await undo.click()
  await page.getByRole('button', { name: 'Show grid', exact: true }).click()
  await page.getByRole('button', { name: 'Snap to grid', exact: true }).click()
  await page.getByLabel('Grid spacing').fill('2')
  await page.getByLabel('Grid spacing').press('Tab')
  await page.getByLabel('Units').selectOption('cm')
  await page.reload()
  await expect(undo).toBeDisabled()
  await expect(redo).toBeDisabled()
  await expect(page.getByLabel('Selected terrain')).toHaveCount(0)
  await expect(page.getByLabel('Units')).toHaveValue('in')
  await expect(page.getByLabel('Grid spacing')).toHaveValue('1')
  await expect(page.getByRole('button', { name: 'Show grid', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByRole('button', { name: 'Snap to grid', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: 'Building 1', exact: true }).click()
  await expect(page.getByLabel('Terrain width')).toHaveValue('6')
  await expect(page.getByLabel('X position')).toHaveValue('7.125')
  await expect(page.getByLabel('Y position')).toHaveValue('8.25')
  await expect(page.getByLabel('Rotation (degrees)')).toHaveValue('30')
})

test('selection and all editor preferences preserve redo and stay unchanged through history', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create layout' }).click()
  await page.getByLabel('Building footprint preview').dragTo(page.getByRole('region', { name: 'Terrain board' }), { targetPosition: { x: 180, y: 180 } })
  await page.getByRole('button', { name: 'Duplicate terrain' }).click()
  await page.getByLabel('Terrain height').fill('6')
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  const undo = page.getByRole('button', { name: 'Undo', exact: true })
  const redo = page.getByRole('button', { name: 'Redo', exact: true })
  await undo.click()
  await page.getByRole('button', { name: 'Building 1', exact: true }).click()
  await page.getByRole('button', { name: 'Show grid', exact: true }).click()
  await page.getByRole('button', { name: 'Snap to grid', exact: true }).click()
  await page.getByLabel('Grid spacing').fill('2')
  await page.getByLabel('Grid spacing').press('Tab')
  await page.getByLabel('Units').selectOption('cm')
  await expect(redo).toBeEnabled()
  await redo.click()
  await expect(page.getByRole('button', { name: 'Building 1', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Building 2', exact: true }).click()
  await expect(page.getByLabel('Terrain height')).toHaveValue('15.24')
  await undo.click()
  await expect(page.getByLabel('Terrain height')).toHaveValue('10.16')
  await expect(page.getByLabel('Units')).toHaveValue('cm')
  await expect(page.getByLabel('Grid spacing')).toHaveValue('5.08')
  await expect(page.getByRole('button', { name: 'Show grid', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Snap to grid', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

test('unchanged Apply preserves redo and consumes no undo step, while a new edit clears redo', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create layout' }).click()
  const undo = page.getByRole('button', { name: 'Undo', exact: true })
  const redo = page.getByRole('button', { name: 'Redo', exact: true })
  await expect(undo).toBeDisabled()
  await page.getByLabel('Building footprint preview').dragTo(page.getByRole('region', { name: 'Terrain board' }), { targetPosition: { x: 180, y: 180 } })
  await page.getByLabel('Terrain width').fill('8')
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  await undo.click()
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  await expect(redo).toBeEnabled()
  await redo.click()
  await expect(page.getByLabel('Terrain width')).toHaveValue('8')
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  await undo.click()
  await expect(page.getByLabel('Terrain width')).toHaveValue('6')
  await page.getByLabel('Terrain height').fill('5')
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  await expect(redo).toBeDisabled()
})

test('invalid saved layouts still show recovery guidance and a fresh history baseline', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('terrain-planner.current-layout.v1', '{"version":1,"board":{"width":0}}'))
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('Your saved layout could not be loaded')
  await page.getByRole('button', { name: 'Create layout' }).click()
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
  await expect(page.getByRole('status')).toContainText('Saved locally')
})

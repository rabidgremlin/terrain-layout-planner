import { test, expect } from '@playwright/test'

test('create a custom game board, place and move independent terrain, and resume after reload', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Game').selectOption('custom')
  await page.getByLabel('Board size').selectOption('36')
  await page.getByRole('button', { name: 'Create layout' }).click()
  await expect(page.getByRole('heading', { name: 'Custom game · 36″ × 36″' })).toBeVisible()
  const board = page.getByRole('region', { name: 'Terrain board' })
  const bounds = (await board.boundingBox())!
  await page.locator('.preview').dragTo(board, { targetPosition: { x: 160, y: 140 } })
  await expect(page.getByText('1 terrain piece')).toBeVisible()
  // A centre grab at (8,7) inches places the 6×4 piece at (5,5).
  await expect(page.getByLabel('Selected terrain')).toContainText('5.0″, 5.0″')
  await page.mouse.move(bounds.x + 120, bounds.y + 120)
  await page.mouse.down()
  await page.mouse.move(bounds.x + 160, bounds.y + 180, { steps: 10 })
  await page.mouse.up()
  await expect(page.getByLabel('Selected terrain')).toContainText('7.0″, 8.0″')
  await page.locator('.preview').dragTo(board, { targetPosition: { x: 200, y: 200 } })
  await expect(page.getByText('2 terrain pieces')).toBeVisible()
  await page.mouse.move(bounds.x + 150, bounds.y + 170)
  await page.mouse.down()
  await page.mouse.move(bounds.x + 210, bounds.y + 210, { steps: 10 })
  await page.mouse.up()
  await expect(page.getByLabel('Selected terrain')).toContainText('10.0″, 10.0″')
  await page.getByRole('button', { name: 'Building 1', exact: true }).click()
  await expect(page.getByLabel('Selected terrain')).toContainText('7.0″, 8.0″')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Custom game · 36″ × 36″' })).toBeVisible()
  await expect(page.getByText('2 terrain pieces')).toBeVisible()
  await page.mouse.click(bounds.x + 150, bounds.y + 170)
  await expect(page.getByLabel('Selected terrain')).toContainText('7.0″, 8.0″')
  await page.getByRole('button', { name: 'Building 2', exact: true }).click()
  await expect(page.getByLabel('Selected terrain')).toContainText('10.0″, 10.0″')
})

test('create a standard Firefight board', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create layout' }).click()
  await expect(page.getByRole('heading', { name: 'Firefight · 48″ × 48″' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Firefight · 48″ × 48″' })).toBeVisible()
})

test('custom dimensions must be positive and preserve fractional physical size', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Board size').selectOption('custom')
  await page.getByLabel('Width (inches)').fill('0')
  await page.getByRole('button', { name: 'Create layout' }).click()
  await expect(page.getByRole('alert')).toContainText('positive')
  await page.getByLabel('Width (inches)').fill('8.5')
  await page.getByLabel('Height (inches)').fill('10')
  await page.getByRole('button', { name: 'Create layout' }).click()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Firefight · 8.5″ × 10″' })).toBeVisible()
})

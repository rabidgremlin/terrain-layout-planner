import { test, expect } from '@playwright/test'

test('shared tag settings are drafted, saved in one step, and restored after reload', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create layout' }).click()
  const board = page.getByRole('region', { name: 'Terrain board' })
  await page.getByLabel('Building footprint preview').dragTo(board, { targetPosition: { x: 180, y: 180 } })
  await expect(page.getByText('Blocks LOS: Yes')).toBeVisible()
  const trigger = page.getByRole('button', { name: 'Layout settings' })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Layout settings' })
  const sight = dialog.getByRole('listitem', { name: 'Sight Blocking', exact: true }).getByRole('checkbox')
  await expect(sight).toBeChecked()
  await sight.uncheck()
  await dialog.getByLabel('New tag').fill('  Custom  ')
  await dialog.getByRole('button', { name: 'Add tag' }).click()
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await expect(trigger).toBeFocused()
  await expect(page.getByText('Blocks LOS: Yes')).toBeVisible()
  await trigger.click()
  await expect(dialog.getByRole('listitem', { name: 'Custom', exact: true })).toHaveCount(0)
  await sight.uncheck()
  await dialog.getByLabel('New tag').fill(' Custom ')
  await dialog.getByRole('button', { name: 'Add tag' }).click()
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Blocks LOS: No')).toBeVisible()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByText('Blocks LOS: Yes')).toBeVisible()
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(page.getByText('Blocks LOS: No')).toBeVisible()
  await page.reload()
  await trigger.click()
  await expect(dialog.getByRole('listitem', { name: 'Custom', exact: true })).toBeVisible()
  await expect(sight).not.toBeChecked()
})

test('any blocking tag blocks, shared flags apply to later placements, and no-op save preserves redo', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create layout' }).click()
  const board = page.getByRole('region', { name: 'Terrain board' })
  await page.getByLabel('Building footprint preview').dragTo(board, { targetPosition: { x: 180, y: 180 } })
  await page.getByRole('checkbox', { name: 'Dense', exact: true }).check()
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  const settings = page.getByRole('button', { name: 'Layout settings' })
  await settings.click()
  const dialog = page.getByRole('dialog')
  const flag = (name: string) => dialog.getByRole('listitem', { name, exact: true }).getByRole('checkbox')
  await expect(dialog.getByRole('listitem', { name: 'Dense', exact: true })).toContainText('1 piece')
  await flag('Sight Blocking').uncheck()
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Blocks LOS: Yes')).toBeVisible()
  await settings.click()
  await flag('Dense').uncheck()
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Blocks LOS: No')).toBeVisible()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await settings.click()
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Redo', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await page.getByLabel('Building footprint preview').dragTo(board, { targetPosition: { x: 360, y: 360 } })
  await expect(page.getByText('Blocks LOS: No')).toBeVisible()
  await page.getByRole('checkbox', { name: 'Sight Blocking', exact: true }).uncheck()
  await page.getByRole('checkbox', { name: 'Impassable', exact: true }).uncheck()
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  await expect(page.getByText('Blocks LOS: No')).toBeVisible()
})

test('tag names validate without committing and old planner data is reset', async ({ page }) => {
  await page.addInitScript(() => {
    if (!sessionStorage.getItem('seeded')) {
      localStorage.setItem('terrain-planner.current-layout.v1', '{"version":1}')
      localStorage.setItem('unrelated', 'keep')
      sessionStorage.setItem('seeded', 'yes')
    }
  })
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Create layout' })).toBeVisible()
  expect(await page.evaluate(() => [localStorage.getItem('terrain-planner.current-layout.v1'), localStorage.getItem('unrelated')])).toEqual([null, 'keep'])
  await page.getByRole('button', { name: 'Create layout' }).click()
  await page.getByRole('button', { name: 'Layout settings' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('New tag').fill('   ')
  await dialog.getByRole('button', { name: 'Add tag' }).click()
  await expect(dialog.getByRole('alert')).toContainText('Enter a tag name')
  await dialog.getByLabel('New tag').fill(' cOvEr ')
  await dialog.getByRole('button', { name: 'Add tag' }).click()
  await expect(dialog.getByRole('alert')).toContainText('already exists')
  await dialog.getByLabel('New tag').fill('Unused')
  await dialog.getByRole('button', { name: 'Add tag' }).click()
  await expect(dialog.getByRole('listitem', { name: 'Unused', exact: true })).toContainText('0 pieces')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Layout settings' }).click()
  await expect(dialog.getByRole('listitem', { name: 'Unused', exact: true })).toBeVisible()
  await expect(dialog.getByRole('listitem', { name: 'Sight Blocking', exact: true }).getByRole('checkbox')).toBeChecked()
  await expect(dialog.getByRole('listitem', { name: 'Dense', exact: true }).getByRole('checkbox')).toBeChecked()
})

test('custom memberships and colour commit together and remain independent across pieces', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create layout' }).click()
  await page.getByRole('button', { name: 'Layout settings' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('New tag').fill('Magic mist')
  await dialog.getByRole('button', { name: 'Add tag' }).click()
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  const board = page.getByRole('region', { name: 'Terrain board' })
  await page.getByLabel('Forest footprint preview').dragTo(board, { targetPosition: { x: 180, y: 180 } })
  await page.getByRole('button', { name: 'Duplicate terrain' }).click()
  await page.getByRole('checkbox', { name: 'Magic mist', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Cover', exact: true }).uncheck()
  await page.getByLabel('Colour', { exact: true }).fill('#123456')
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Magic mist', exact: true })).not.toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Cover', exact: true })).toBeChecked()
  await expect(page.getByLabel('Colour', { exact: true })).toHaveValue('#718c63')
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await page.getByRole('button', { name: 'Forest 1', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Magic mist', exact: true })).not.toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Cover', exact: true })).toBeChecked()
  await page.reload()
  await page.getByRole('button', { name: 'Forest 2', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Magic mist', exact: true })).toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Cover', exact: true })).not.toBeChecked()
  await expect(page.getByLabel('Colour', { exact: true })).toHaveValue('#123456')
})

test('keyboard opens and dismisses the modal without moving the board', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create layout' }).click()
  const board = page.getByRole('region', { name: 'Terrain board' })
  const before = await board.boundingBox()
  const trigger = page.getByRole('button', { name: 'Layout settings' })
  await trigger.focus()
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: 'Layout settings' })
  await expect(dialog.getByRole('tab', { name: 'Tags' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('textbox', { name: 'Tag name: Impassable', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('checkbox', { name: 'Impassable Blocks LOS' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
  expect(await board.boundingBox()).toEqual(before)
})
